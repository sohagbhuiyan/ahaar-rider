import * as SplashScreen from 'expo-splash-screen';
import { StatusBar } from 'expo-status-bar';
import { useEffect, useState } from 'react';
import { Image, StyleSheet, View } from 'react-native';
import Animated, {
  Easing,
  interpolate,
  useAnimatedStyle,
  useReducedMotion,
  useSharedValue,
  withDelay,
  withRepeat,
  withSequence,
  withSpring,
  withTiming,
  type SharedValue,
} from 'react-native-reanimated';

import { useAuthStore } from '@/lib/auth/authStore';
import { colors } from '@/lib/theme';

/**
 * Must equal `imageWidth` of the `expo-splash-screen` plugin in app.json, and
 * `ART_FRACTION` must match the baked plate (`assets/images/brand/splash-plate.png`,
 * generated by the customer app's `scripts/build-splash-plate.js` run from this
 * project's root). The first frame here redraws the native splash exactly, so
 * the hand-over is invisible and the animation simply begins.
 */
const PLATE_SIZE = 220;
const ART_FRACTION = 0.58;
const MARK = require('@/assets/images/brand/ahaar-mark.png');
const MARK_WIDTH = Math.round(PLATE_SIZE * ART_FRACTION);
const MARK_HEIGHT = Math.round((MARK_WIDTH * 448) / 491);

const RING_SIZE = 300;
const LIFT = 40;
const BAR_WIDTH = 132;

const MIN_VISIBLE_MS = 1600;
const REDUCED_MIN_VISIBLE_MS = 400;
const MAX_VISIBLE_MS = 4500;
const EXIT_MS = 420;

/**
 * Rider guide: white text only on Secondary #E04E0C, never on the #FF7A00
 * primary — so the splash field is the secondary brand colour.
 */
const FIELD = colors.brand[700];

let nativeSplashHidden = false;
function hideNativeSplash() {
  if (nativeSplashHidden) return;
  nativeSplashHidden = true;
  SplashScreen.hideAsync().catch(() => undefined);
}

/**
 * The rider app's opening moment: the AHAAR mark on a white disc settles with
 * a spring and lifts, ripples pulse out, "AHAAR · RIDER PARTNER" fades in over
 * a loading bar, then the layer fades away. Waits for the stored session to be
 * read (so the gateway never flashes the sign-in buttons), shows at least
 * `MIN_VISIBLE_MS`, never more than `MAX_VISIBLE_MS`. Reduce-motion skips the
 * spring and ripples.
 */
export function RiderSplash() {
  const reduceMotion = useReducedMotion();
  const isInitializing = useAuthStore((s) => s.isInitializing);

  const [minElapsed, setMinElapsed] = useState(false);
  const [timedOut, setTimedOut] = useState(false);
  const [finished, setFinished] = useState(false);

  const pop = useSharedValue(1);
  const lift = useSharedValue(0);
  const ripple = useSharedValue(0);
  const intro = useSharedValue(0);
  const progress = useSharedValue(0);
  const exit = useSharedValue(0);

  const leaving = (!isInitializing && minElapsed) || timedOut;

  useEffect(() => {
    const visibleFor = reduceMotion ? REDUCED_MIN_VISIBLE_MS : MIN_VISIBLE_MS;
    const easeOut = Easing.out(Easing.cubic);

    if (!reduceMotion) {
      pop.value = withDelay(
        120,
        withSequence(
          withTiming(0.92, { duration: 160, easing: Easing.out(Easing.quad) }),
          withSpring(1, { damping: 8, stiffness: 150 }),
        ),
      );
      lift.value = withDelay(320, withSpring(-LIFT, { damping: 15, stiffness: 110 }));
      ripple.value = withDelay(
        250,
        withRepeat(withTiming(1, { duration: 1800, easing: easeOut }), -1, false),
      );
    }
    intro.value = withDelay(reduceMotion ? 0 : 420, withTiming(1, { duration: 650, easing: easeOut }));
    progress.value = withTiming(1, { duration: visibleFor, easing: Easing.inOut(Easing.cubic) });

    const minTimer = setTimeout(() => setMinElapsed(true), visibleFor);
    const maxTimer = setTimeout(() => setTimedOut(true), MAX_VISIBLE_MS);
    const nativeTimer = setTimeout(hideNativeSplash, 1000);
    return () => {
      clearTimeout(minTimer);
      clearTimeout(maxTimer);
      clearTimeout(nativeTimer);
    };
  }, [reduceMotion, pop, lift, ripple, intro, progress]);

  useEffect(() => {
    if (!leaving) return;
    hideNativeSplash();
    const duration = reduceMotion ? 200 : EXIT_MS;
    exit.value = withTiming(1, { duration, easing: Easing.in(Easing.cubic) });
    const timer = setTimeout(() => setFinished(true), duration + 50);
    return () => clearTimeout(timer);
  }, [leaving, reduceMotion, exit]);

  const rootStyle = useAnimatedStyle(() => ({ opacity: 1 - exit.value }));
  const liftStyle = useAnimatedStyle(() => ({ transform: [{ translateY: lift.value }] }));
  const plateStyle = useAnimatedStyle(() => ({
    transform: [{ scale: pop.value * (1 + exit.value * 0.12) }],
  }));
  const glowStyle = useAnimatedStyle(() => ({
    opacity: intro.value,
    transform: [{ scale: interpolate(intro.value, [0, 1], [0.6, 1]) }],
  }));
  const textStyle = useAnimatedStyle(() => ({
    opacity: intro.value * (1 - exit.value),
    transform: [{ translateY: (1 - intro.value) * 12 + exit.value * 16 }],
  }));
  const barFillStyle = useAnimatedStyle(() => ({ width: progress.value * BAR_WIDTH }));

  if (finished) return null;

  return (
    <Animated.View
      accessible
      accessibilityRole="progressbar"
      accessibilityLabel="Loading AHAAR Rider"
      style={[
        StyleSheet.absoluteFill,
        styles.root,
        rootStyle,
        { pointerEvents: leaving ? 'none' : 'auto' },
      ]}
    >
      <StatusBar style="light" />
      <Animated.View style={[styles.stage, liftStyle]}>
        <Animated.View style={[styles.glow, glowStyle]} />
        <Ripple progress={ripple} visibility={intro} offset={0} />
        <Ripple progress={ripple} visibility={intro} offset={0.5} />
        <Animated.View style={[styles.plate, plateStyle]}>
          <Image
            source={MARK}
            resizeMode="contain"
            fadeDuration={0}
            onLoadEnd={hideNativeSplash}
            style={{ width: MARK_WIDTH, height: MARK_HEIGHT }}
          />
        </Animated.View>
      </Animated.View>

      <Animated.View style={[styles.below, textStyle]}>
        <Animated.Text style={styles.brand}>AHAAR</Animated.Text>
        <View style={styles.pill}>
          <Animated.Text style={styles.pillText}>RIDER PARTNER</Animated.Text>
        </View>
        <View style={styles.bar}>
          <Animated.View style={[styles.barFill, barFillStyle]} />
        </View>
      </Animated.View>
    </Animated.View>
  );
}

function Ripple({
  progress,
  visibility,
  offset,
}: {
  progress: SharedValue<number>;
  visibility: SharedValue<number>;
  offset: number;
}) {
  const style = useAnimatedStyle(() => {
    const t = (progress.value + offset) % 1;
    return {
      opacity: interpolate(t, [0, 0.15, 1], [0, 0.5, 0]) * visibility.value,
      transform: [{ scale: interpolate(t, [0, 1], [0.55, 1.55]) }],
    };
  });
  return <Animated.View style={[styles.ring, style]} />;
}

const styles = StyleSheet.create({
  root: {
    zIndex: 1000,
    elevation: 1000,
    alignItems: 'center',
    justifyContent: 'center',
    // Matches `backgroundColor` of the expo-splash-screen plugin in app.json.
    backgroundColor: FIELD,
  },
  stage: {
    width: RING_SIZE,
    height: RING_SIZE,
    alignItems: 'center',
    justifyContent: 'center',
  },
  glow: {
    position: 'absolute',
    width: RING_SIZE * 0.92,
    height: RING_SIZE * 0.92,
    borderRadius: RING_SIZE,
    backgroundColor: 'rgba(255,255,255,0.14)',
  },
  ring: {
    position: 'absolute',
    width: RING_SIZE,
    height: RING_SIZE,
    borderRadius: RING_SIZE / 2,
    borderWidth: 2,
    borderColor: 'rgba(255,255,255,0.55)',
  },
  plate: {
    width: PLATE_SIZE,
    height: PLATE_SIZE,
    borderRadius: PLATE_SIZE / 2,
    alignItems: 'center',
    justifyContent: 'center',
    backgroundColor: colors.surface.DEFAULT,
    shadowColor: '#431407',
    shadowOpacity: 0.25,
    shadowRadius: 18,
    shadowOffset: { width: 0, height: 8 },
    elevation: 8,
  },
  below: {
    position: 'absolute',
    top: '50%',
    left: 0,
    right: 0,
    alignItems: 'center',
    marginTop: RING_SIZE / 2 - LIFT + 8,
  },
  brand: {
    fontSize: 30,
    fontWeight: '900',
    letterSpacing: 6,
    color: colors.text.inverse,
  },
  pill: {
    marginTop: 8,
    paddingHorizontal: 14,
    paddingVertical: 5,
    borderRadius: 999,
    backgroundColor: 'rgba(255,255,255,0.18)',
    borderWidth: 1,
    borderColor: 'rgba(255,255,255,0.35)',
  },
  pillText: {
    fontSize: 12,
    fontWeight: '800',
    letterSpacing: 3,
    color: colors.text.inverse,
  },
  bar: {
    marginTop: 22,
    width: BAR_WIDTH,
    height: 4,
    borderRadius: 2,
    overflow: 'hidden',
    backgroundColor: 'rgba(255,255,255,0.28)',
  },
  barFill: {
    height: 4,
    borderRadius: 2,
    backgroundColor: colors.text.inverse,
  },
});
